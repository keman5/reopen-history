import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { issues, privacy, repository, support, updated } from '../store/content.mjs';

const { version } = JSON.parse(await readFile('package.json', 'utf8'));
const escape = text => String(text).replace(/[&<>"']/g, ch => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[ch]));
const link = ({ label, href }) => '<a href="' + escape(href) + '"' + (href.startsWith('https://') ? ' target="_blank" rel="noopener noreferrer"' : '') + '>' + escape(label) + '</a>';
function section(entry) {
  return '<section><h3>' + escape(entry.title) + '</h3>' +
    (entry.paragraphs || []).map(p => '<p>' + escape(p) + '</p>').join('') +
    (entry.items ? '<ul>' + entry.items.map(p => '<li>' + escape(p) + '</li>').join('') + '</ul>' : '') +
    (entry.links ? '<ul class="links">' + entry.links.map(l => '<li>' + link(l) + '</li>').join('') + '</ul>' : '') + '</section>';
}
function languages(data) {
  return '<nav class="language-nav" aria-label="Language"><a href="#zh">简体中文</a><a href="#en">English</a></nav>' +
    [['zh', 'zh-CN'], ['en', 'en']].map(([key, lang]) => '<article class="language-block" id="' + key + '" lang="' + lang + '" aria-labelledby="heading-' + key + '"><h2 id="heading-' + key + '">' + escape(data[key].title) + '</h2><p class="intro">' + escape(data[key].intro) + '</p>' + data[key].sections.map(section).join('') + '</article>').join('');
}
function page(title, body, bundled = false) {
  const home = bundled ? 'history.html' : 'index.html';
  const icon = bundled ? 'icons/icon128.png' : 'icon128.png';
  return '<!doctype html>\n<!-- Generated by scripts/build-store-pages.mjs from store/content.mjs. -->\n' +
    '<html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="color-scheme" content="light">' +
    '<meta name="description" content="Reopen History — 本地标签页恢复扩展的隐私政策与支持。Privacy and support for a local closed-tab recovery extension.">' +
    '<title>' + escape(title) + ' · Reopen History</title><link rel="icon" href="' + icon + '"><link rel="stylesheet" href="' + (bundled ? 'legal.css' : 'site.css') + '"></head>\n' +
    '<body><a class="skip" href="#main">跳到正文 / Skip to content</a><header><a class="brand" href="' + home + '"><img src="' + icon + '" alt="" width="36" height="36"><span>Reopen History</span></a><nav aria-label="页面 / Pages"><a href="privacy.html">隐私 / Privacy</a><a href="support.html">支持 / Support</a></nav></header>' +
    '<main id="main"><h1>' + escape(title) + '</h1><p class="meta">生效 / Updated: ' + updated + ' · Version ' + escape(version) + ' · Maintainer: keman5</p>' + body + '</main>' +
    '<footer><p>由 keman5 维护 / Maintained by keman5 · ' + link({ label: 'GitHub Issues', href: issues }) + '</p><p>扩展无广告与统计 / No extension ads or analytics</p></footer></body></html>\n';
}
function markdown(data) {
  return '# ' + data.en.title + ' / ' + data.zh.title + '\n\nEffective / updated: ' + updated + '\n\nMaintainer: [keman5](' + repository + ')\n\n' +
    ['en', 'zh'].map(locale => '## ' + data[locale].title + '\n\n' + data[locale].intro + '\n\n' +
      data[locale].sections.map(entry => '### ' + entry.title + '\n\n' +
        (entry.paragraphs || []).join('\n\n') +
        (entry.items ? '\n' + entry.items.map(p => '- ' + p).join('\n') : '') +
        (entry.links ? '\n\n' + entry.links.map(l => '[' + l.label + '](' + (l.href === 'privacy.html' ? 'PRIVACY.md' : l.href) + ')').join(' · ') : '') + '\n').join('\n')).join('\n');
}

const home = '<p class="intro">一键恢复已关闭标签页，在本机搜索最近记录。<br><span lang="en">Reopen closed tabs and search recent records on your device.</span></p>' +
  '<nav class="links actions" aria-label="帮助 / Help"><a href="privacy.html">隐私政策 / Privacy policy</a><a href="support.html">使用帮助 / Get support</a></nav>' +
  '<div class="lead-note">无需账号、无广告和遥测。浏览记录保留在浏览器本地。<br><span lang="en">No account, ads or telemetry. Browsing records remain in browser-local storage.</span></div>' +
  '<h2>桌面浏览器 / Desktop browsers</h2><p>Chrome / Edge 120+ · Firefox 142+ · Safari 16+ on macOS 13+</p>' +
  '<p>Safari 仅恢复保存的网址，不恢复表单或完整会话。<br><span lang="en">Safari reopens saved URLs only, without form or full session state.</span></p>' +
  '<ul class="links"><li>' + link({ label: '源代码 / Source', href: repository }) + '</li><li>' + link({ label: '反馈问题 / Report an issue', href: issues }) + '</li></ul>';
await mkdir('docs', { recursive: true });
await writeFile('docs/index.html', page('恢复已关闭标签 / Reopen History', home));
for (const [name, data] of [['privacy', privacy], ['support', support]]) {
  await writeFile('docs/' + name + '.html', page(data.zh.title + ' / ' + data.en.title, languages(data)));
  await writeFile('extension/' + name + '.html', page(data.zh.title + ' / ' + data.en.title, languages(data), true));
  await writeFile((name === 'privacy' ? 'PRIVACY' : 'SUPPORT') + '.md', markdown(data));
}
await cp('store/styles.css', 'docs/site.css');
await cp('store/styles.css', 'extension/legal.css');
await cp('extension/icons/icon128.png', 'docs/icon128.png');
await writeFile('docs/.nojekyll', '');
const output = join(homedir(), 'downloads', 'dist');
const site = join(output, 'reopen-history-store-pages-v' + version);
await rm(site, { recursive: true, force: true });
await mkdir(site, { recursive: true });
for (const file of ['index.html', 'privacy.html', 'support.html', 'site.css', 'icon128.png', '.nojekyll']) await cp('docs/' + file, join(site, file));
const archive = join(output, 'reopen-history-store-pages-' + version + '.zip');
await rm(archive, { force: true });
execFileSync('/usr/bin/zip', ['-qr', archive, '.'], { cwd: site });
console.log('Built public privacy/support pages: ' + site);
